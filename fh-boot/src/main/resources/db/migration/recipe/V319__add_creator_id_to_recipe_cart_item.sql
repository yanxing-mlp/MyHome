-- recipe 域（V3xx 号段续）：购物车条目加"加购人"。
--
-- 口径与 V316 那三张表一致：可空、不建索引、只存 id 不存昵称，昵称由前端查账号字典。
--
-- 【为什么这一列有独立一条迁移，没并进 V316】
-- V316 那一批做的时候，购物车还是"家庭共用单车、无用户维度"（见 V304 表注释），
-- 加购人这个概念当时不存在。V5xx 引入账号体系后，"谁加的这道菜"才有意义。
--
-- 【为什么不在这里回填存量】
-- 回填要读 app_user，而 app_user 是 V500 建的。本条靠 out-of-order 在已有库上补跑时
-- app_user 确实已存在，但从零重建时迁移按版本号顺序执行，V319 排在 V500 前面，
-- 那时 app_user 还不存在，子查询会直接报错。所以加列留在本域，存量回填放 user 域 V504。
--
-- 【家庭共用单车不变】仍是"一菜一行"（uk_recipe 唯一约束没动），这一列只记录
-- 最后把它加进来的人；别人改量/改做法不重写它，跟 recipe_order 的下单人一个口径。
ALTER TABLE `recipe_cart_item`
  ADD COLUMN `creator_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '加购人 app_user.id（谁把这道菜加进车的；别人改量/改做法不动它）' AFTER `qty`;
